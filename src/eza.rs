//! Export the part of a Glyfuse theme supported by eza's `theme.yml`.

use glyfuse::{Icon, Kind, Theme};
use std::collections::BTreeMap;

pub fn render(theme: &Theme) -> String {
    let mut filenames = BTreeMap::<&str, &Icon>::new();
    let mut extensions = BTreeMap::<&str, &Icon>::new();

    for rule in &theme.rules {
        // eza accepts one Unicode scalar per icon, and has no path-glob matcher.
        if rule.icon.glyph.chars().count() != 1 {
            continue;
        }
        match rule.kind {
            Kind::File | Kind::Folder if !rule.pattern.contains(['/', '\\']) => {
                // eza's filenames table cannot distinguish files from directories.
                filenames.insert(&rule.pattern, &rule.icon);
            }
            Kind::Extension if !rule.pattern.contains('.') => {
                // eza matches the final extension only, not compound extensions.
                extensions.insert(&rule.pattern, &rule.icon);
            }
            _ => {}
        }
    }

    let mut output = format!(
        "# Generated by glyfuse export eza from {:?}.\n# Only icons are customized; eza keeps its filename colors.\n",
        theme.name
    );
    for (section, icons) in [("filenames", filenames), ("extensions", extensions)] {
        output.push_str(section);
        output.push_str(":\n");
        for (name, icon) in icons {
            output.push_str(&format!(
                "  {}:\n    icon:\n      glyph: {}\n      style:\n        foreground: {}\n",
                serde_json::to_string(name).expect("valid string"),
                serde_json::to_string(&icon.glyph).expect("valid glyph"),
                serde_json::to_string(&icon.color).expect("valid color"),
            ));
        }
    }
    output
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn exports_icons_and_rgb_without_recoloring_names() {
        let theme = Theme::parse(
            r##"{"format":1,"name":"Example","fallbacks":{"file":{"glyph":"?","color":"#AAAAAA"},"folder":{"glyph":"+","color":"#BBBBBB"}},"rules":[{"kind":"file","pattern":"Cargo.toml","icon":{"glyph":"🦀","color":"#FF0000"}},{"kind":"extension","pattern":"rs","icon":{"glyph":"R","color":"#00FF00"}},{"kind":"extension","pattern":"tar.gz","icon":{"glyph":"Z","color":"#0000FF"}},{"kind":"path","pattern":"**/src/*.rs","icon":{"glyph":"P","color":"#123456"}},{"kind":"folder","pattern":"src","icon":{"glyph":"📁","color":"#FFFFFF"}},{"kind":"file","pattern":"multiple","icon":{"glyph":"AB","color":"#123456"}}]}"##,
        ).unwrap();
        let yaml = render(&theme);
        assert!(yaml.contains("\"Cargo.toml\":\n    icon:\n      glyph: \"🦀\"\n      style:\n        foreground: \"#FF0000\""));
        assert!(yaml.contains("\"src\":\n    icon:\n      glyph: \"📁\""));
        assert!(yaml.contains("\"rs\":\n    icon:\n      glyph: \"R\""));
        assert!(!yaml.contains("tar.gz"));
        assert!(!yaml.contains("multiple"));
        assert!(!yaml.contains("**/src"));
        assert!(!yaml.contains("filename:"));
    }

    #[test]
    fn latest_duplicate_wins() {
        let mut theme = Theme::load("material").unwrap();
        theme.rules.push(glyfuse::Rule {
            kind: Kind::File,
            pattern: "Cargo.toml".into(),
            icon: Icon {
                glyph: "X".into(),
                color: "#123456".into(),
            },
            expanded: None,
            source_icon: None,
        });
        let yaml = render(&theme);
        assert!(yaml.contains("\"Cargo.toml\":\n    icon:\n      glyph: \"X\"\n      style:\n        foreground: \"#123456\""));
        assert_eq!(yaml.matches("\"Cargo.toml\":").count(), 1);
    }
}
